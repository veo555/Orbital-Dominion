#!/usr/bin/env node
/* Write src/js/41_ai_params.js from a league result.
     node tools/league/export_params.js <tiers.json> [--vf vf.json] [--combat combat.json] [--out src/js/41_ai_params.js]
   tiers.json: {version, theta0:[...], styles:{...}?, tiers:{easy:{theta,think,apm,delay,micro,focus,kite,macro,useV}, normal, hard, master}, meta:{...}}
   vf.json:    output of train_value.py ({model, report}); only the model is embedded.
   Anything not given is taken over from the current 41_ai_params.js. */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..');
const a = process.argv.slice(2), opt = { out: path.join(ROOT, 'src', 'js', '41_ai_params.js') };
for (let i = 1; i < a.length; i++) { if (a[i] === '--vf') opt.vf = a[++i]; else if (a[i] === '--combat') opt.combat = a[++i]; else if (a[i] === '--out') opt.out = path.resolve(a[++i]); }
const cur = require(path.join(__dirname, 'game.js')).sim().__run('JSON.stringify(AI_PARAMS)'), P = JSON.parse(cur);
const T = JSON.parse(fs.readFileSync(a[0], 'utf8'));
if (T.version) P.version = T.version; if (T.theta0) P.theta0 = T.theta0; if (T.styles) P.styles = T.styles; if (T.tiers) P.tiers = T.tiers; if (T.meta) P.meta = T.meta;
if (opt.vf) P.vf = JSON.parse(fs.readFileSync(opt.vf, 'utf8')).model;
if (opt.combat) P.combat = JSON.parse(fs.readFileSync(opt.combat, 'utf8'));
const r5 = (x) => Array.isArray(x) ? x.map(r5) : (typeof x === 'number' ? +x.toFixed(5) : (x && typeof x === 'object' ? Object.fromEntries(Object.entries(x).map(([k, v]) => [k, r5(v)])) : x));
const body = `/* =========================================================================
   41_AI_PARAMS — parameters of the T2 opponent. GENERATED by tools/league/export_params.js from a league run; do not edit by hand.
   theta vectors live in the unit cube (decoded by thetaDecode in 42_ai_agent.js; THETA_SPEC names them); styles are faction priors
   added in the same space; tiers differ in theta (decision quality) and in think rate, APM cap, reaction delay, micro and macro efficiency
   (all with income x1.0). vf = value function V(s) (tools/league/train_value.py); combat = predictor link (tools/league/calib_combat.js).
   See docs/AI_DESIGN.md and docs/AI_LEAGUE_RESULTS.md.
   ========================================================================= */
const AI_PARAMS=${JSON.stringify(r5(P))};
`;
fs.writeFileSync(opt.out, body);
console.log('wrote ' + opt.out + ' (' + body.length + ' bytes), version ' + P.version);
