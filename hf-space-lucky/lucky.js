/* Lucky-manager statistics in plain JS (port of research/manager-diligence: psr, expected_max_sharpe, dsr).
   Parity with the Python implementation is asserted by tests/parity.js against tests/parity.json (generated by Python). */
(function (root) {
  'use strict';
  function erf(x) { // Taylor series (|x|<=3) / continued fraction for erfc (|x|>3); ~1e-15
    var ax = Math.abs(x), s;
    if (ax <= 3) {
      var term = ax, sum = ax, n = 0;
      while (Math.abs(term) > 1e-18 && n < 200) { n++; term *= -ax * ax / n; sum += term / (2 * n + 1); }
      s = 2 / Math.sqrt(Math.PI) * sum;
    } else {
      var f = 0; for (var k = 60; k >= 1; k--) f = k / 2 / (ax + f);
      s = 1 - Math.exp(-ax * ax) / Math.sqrt(Math.PI) / (ax + f);
    }
    return x < 0 ? -s : s;
  }
  function normCdf(x) { return 0.5 * (1 + erf(x / Math.SQRT2)); }
  function normPpf(p) { // Acklam + one Halley step, as in the Python code
    if (p <= 0) return -Infinity; if (p >= 1) return Infinity;
    var a = [-3.969683028665376e+01, 2.209460984245205e+02, -2.759285104469687e+02, 1.383577518672690e+02, -3.066479806614716e+01, 2.506628277459239e+00],
        b = [-5.447609879822406e+01, 1.615858368580409e+02, -1.556989798598866e+02, 6.680131188771972e+01, -1.328068155288572e+01],
        c = [-7.784894002430293e-03, -3.223964580411365e-01, -2.400758277161838e+00, -2.549732539343734e+00, 4.374664141464968e+00, 2.938163982698783e+00],
        d = [7.784695709041462e-03, 3.224671290700398e-01, 2.445134137142996e+00, 3.754408661907416e+00], pl = 0.02425, x, q, r;
    if (p < pl) { q = Math.sqrt(-2 * Math.log(p)); x = (((((c[0]*q+c[1])*q+c[2])*q+c[3])*q+c[4])*q+c[5]) / ((((d[0]*q+d[1])*q+d[2])*q+d[3])*q+1); }
    else if (p <= 1 - pl) { q = p - 0.5; r = q*q; x = (((((a[0]*r+a[1])*r+a[2])*r+a[3])*r+a[4])*r+a[5])*q / (((((b[0]*r+b[1])*r+b[2])*r+b[3])*r+b[4])*r+1); }
    else { q = Math.sqrt(-2 * Math.log(1 - p)); x = -(((((c[0]*q+c[1])*q+c[2])*q+c[3])*q+c[4])*q+c[5]) / ((((d[0]*q+d[1])*q+d[2])*q+d[3])*q+1); }
    var e = normCdf(x) - p, u = e * Math.sqrt(2 * Math.PI) * Math.exp(x * x / 2);
    return x - u / (1 + x * u / 2);
  }
  function moments(r) { // mean, std(ddof=1), skew, kurtosis (non-excess)
    var n = r.length, m = 0, i; for (i = 0; i < n; i++) m += r[i]; m /= n;
    var ss = 0; for (i = 0; i < n; i++) ss += (r[i] - m) * (r[i] - m);
    var s1 = Math.sqrt(ss / (n - 1)), s0 = Math.sqrt(ss / n), g3 = 0, g4 = 0;
    for (i = 0; i < n; i++) { var z = (r[i] - m) / s0; g3 += z*z*z; g4 += z*z*z*z; }
    return { mean: m, sd: s1, skew: g3 / n, kurt: g4 / n };
  }
  function sharpe(r) { var mo = moments(r); return mo.mean / mo.sd; }
  function psr(r, bench) {
    var mo = moments(r), sr = mo.mean / mo.sd, f = 1 - mo.skew * sr + (mo.kurt - 1) / 4 * sr * sr;
    return f <= 0 ? NaN : normCdf((sr - (bench || 0)) * Math.sqrt(r.length - 1) / Math.sqrt(f));
  }
  var EG = 0.5772156649015329;
  function expectedMaxSharpe(n, v) { return n < 2 ? 0 : Math.sqrt(v) * ((1 - EG) * normPpf(1 - 1 / n) + EG * normPpf(1 - 1 / (n * Math.E))); }
  function dsr(r, n, v) { return psr(r, expectedMaxSharpe(n, v)); }
  function rng(seed) { var a = seed >>> 0; return function () { a = (a + 0x6D2B79F5) >>> 0; var t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
  function gauss(rand) { var u = 1 - rand(), v = rand(); return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v); }
  /* One universe of N zero-skill managers with T monthly returns (annual vol 8%). Returns best manager's stats. */
  function universe(N, T, rand) {
    var sig = 0.08 / Math.sqrt(12), srs = new Array(N), best = -1, bi = 0, rows = new Array(N);
    for (var i = 0; i < N; i++) { var r = new Array(T); for (var t = 0; t < T; t++) r[t] = sig * gauss(rand); rows[i] = r; srs[i] = sharpe(r); if (srs[i] > best) { best = srs[i]; bi = i; } }
    var m = 0; srs.forEach(function (x) { m += x; }); m /= N; var v = 0; srs.forEach(function (x) { v += (x - m) * (x - m); }); v /= (N - 1);
    return { bestAnnual: best * Math.sqrt(12), naive: psr(rows[bi], 0), deflated: dsr(rows[bi], N, v) };
  }
  function experiment(N, T, U, seed) {
    var rand = rng(seed), nv = 0, dv = 0, bs = 0;
    for (var u = 0; u < U; u++) { var o = universe(N, T, rand); bs += o.bestAnnual; if (o.naive > 0.95) nv++; if (o.deflated > 0.95) dv++; }
    return { meanBestAnnual: bs / U, naive: nv / U, deflated: dv / U };
  }
  var api = { erf: erf, normCdf: normCdf, normPpf: normPpf, moments: moments, psr: psr, expectedMaxSharpe: expectedMaxSharpe, dsr: dsr, rng: rng, universe: universe, experiment: experiment };
  if (typeof module !== 'undefined' && module.exports) module.exports = api; else root.Lucky = api;
})(typeof self !== 'undefined' ? self : this);
